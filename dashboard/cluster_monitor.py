def http_json(
    url: str, timeout: float = 3.0, headers: dict[str, str] | None = None
) -> tuple[int, Any]:
    """Return (HTTP status, decoded body), including useful error bodies."""

    request = Request(url, headers=headers or {}, method="GET")
    try:
        with urlopen(request, timeout=timeout) as response:
            raw = response.read()
            if not raw:
                return int(response.status), {}
            try:
                return int(response.status), json.loads(raw.decode("utf-8"))
            except (UnicodeDecodeError, json.JSONDecodeError):
                return int(response.status), {"body": raw.decode(errors="replace")}
    except HTTPError as exc:
        try:
            raw = exc.read()
        except OSError:
            raw = b""
        try:
            body: Any = json.loads(raw.decode("utf-8")) if raw else {}
        except (UnicodeDecodeError, json.JSONDecodeError):
            body = {"body": raw.decode(errors="replace")}
        if isinstance(body, dict):
            body.setdefault("error", f"HTTP {exc.code}")
        return int(exc.code), body
    except (OSError, TimeoutError, URLError) as exc:
        return 0, {"error": str(exc)}


def http_post_json(
    url: str,
    body: dict[str, Any],
    timeout: float = 10.0,
    headers: dict[str, str] | None = None,
) -> tuple[int, Any]:
    request_headers = {"Content-Type": "application/json"}
    if headers:
        request_headers.update(headers)
    request = Request(
        url,
        data=json.dumps(body, separators=(",", ":")).encode("utf-8"),
        headers=request_headers,
        method="POST",
    )
    try:
        with urlopen(request, timeout=timeout) as response:
            raw = response.read()
            if not raw:
                return int(response.status), {}
            try:
                return int(response.status), json.loads(raw.decode("utf-8"))
            except (UnicodeDecodeError, json.JSONDecodeError):
                return int(response.status), {"body": raw.decode(errors="replace")}
    except HTTPError as exc:
        try:
            raw = exc.read()
        except OSError:
            raw = b""
        try:
            response_body: Any = json.loads(raw.decode("utf-8")) if raw else {}
        except (UnicodeDecodeError, json.JSONDecodeError):
            response_body = {"body": raw.decode(errors="replace")}
        if isinstance(response_body, dict):
            response_body.setdefault("error", f"HTTP {exc.code}")
        return int(exc.code), response_body
    except (OSError, TimeoutError, URLError) as exc:
        return 0, {"error": str(exc)}


def _read_text(path: str | Path) -> str | None:
    try:
        return Path(path).read_text(encoding="utf-8").strip()
    except OSError:
        return None


def _read_int(path: str | Path) -> int | None:
    value = _read_text(path)
    if value is None:
        return None
    try:
        return int(value)
    except ValueError:
        return None


def _read_meminfo() -> dict[str, int]:
    values: dict[str, int] = {}
    try:
        lines = Path("/proc/meminfo").read_text(encoding="ascii").splitlines()
    except OSError:
        return values
    for line in lines:
        if ":" not in line:
            continue
        key, raw = line.split(":", 1)
        fields = raw.split()
        if not fields:
            continue
        try:
            number = int(fields[0])
        except ValueError:
            continue
        values[key] = number * 1024 if len(fields) > 1 and fields[1] == "kB" else number
    return values


def collect_memory() -> dict[str, int]:
    values = _read_meminfo()
    total = values.get("MemTotal", 0)
    available = values.get("MemAvailable", values.get("MemFree", 0))
    used = max(total - available, 0)
    swap_total = values.get("SwapTotal", 0)
    swap_free = values.get("SwapFree", 0)
    return {
        "total_bytes": total,
        "available_bytes": available,
        "used_bytes": used,
        "swap_total_bytes": swap_total,
        "swap_used_bytes": max(swap_total - swap_free, 0),
    }


def _sensor_name(path: str, fallback: str) -> str:
    label = _read_text(path)
    return label or fallback


def collect_temperatures() -> list[dict[str, Any]]:
    readings: list[dict[str, Any]] = []
    seen: set[str] = set()

    for path in sorted(glob.glob("/sys/class/thermal/thermal_zone*/temp")):
        raw = _read_int(path)
        if raw is None:
            continue
        zone = Path(path).parent.name
        sensor_type = _read_text(Path(path).parent / "type") or zone
        celsius = raw / 1000 if abs(raw) > 200 else float(raw)
        readings.append(
            {
                "name": sensor_type,
                "celsius": round(celsius, 1),
                "source": path,
            }
        )
        seen.add(path)

    for path in sorted(glob.glob("/sys/class/hwmon/hwmon*/temp*_input")):
        if path in seen:
            continue
        raw = _read_int(path)
        if raw is None:
            continue
        base = Path(path).parent
        stem = Path(path).stem.removesuffix("_input")
        name = _sensor_name(base / f"{stem}_label", f"{base.name}/{stem}")
        celsius = raw / 1000 if abs(raw) > 200 else float(raw)
        readings.append(
            {
                "name": name,
                "celsius": round(celsius, 1),
                "source": path,
            }
        )
    return readings


def collect_fans() -> list[dict[str, Any]]:
    readings: list[dict[str, Any]] = []
    for path in sorted(glob.glob("/sys/class/hwmon/hwmon*/fan*_input")):
        raw = _read_int(path)
        if raw is None:
            continue
        base = Path(path).parent
        stem = Path(path).stem.removesuffix("_input")
        name = _sensor_name(base / f"{stem}_label", f"{base.name}/{stem}")
        readings.append({"name": name, "rpm": raw, "source": path})
