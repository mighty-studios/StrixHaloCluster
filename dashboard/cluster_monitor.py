def collect_gpu_memory() -> dict[str, Any]:
    cards: list[dict[str, Any]] = []
    for device_path in sorted(glob.glob("/sys/class/drm/card*/device")):
        card = Path(device_path).parent.name
        values = {
            "vram_total_bytes": _read_int(Path(device_path) / "mem_info_vram_total"),
            "vram_used_bytes": _read_int(Path(device_path) / "mem_info_vram_used"),
            "gtt_total_bytes": _read_int(Path(device_path) / "mem_info_gtt_total"),
            "gtt_used_bytes": _read_int(Path(device_path) / "mem_info_gtt_used"),
        }
        if any(value is not None for value in values.values()):
            cards.append({"card": card, **values})

    pages_limit = _read_int("/sys/module/ttm/parameters/pages_limit")
    return {
        "cards": cards,
        "ttm_limit_bytes": pages_limit * 4096 if pages_limit is not None else None,
    }


def collect_disk_usage(paths: list[Any]) -> list[dict[str, Any]]:
    result: list[dict[str, Any]] = []
    for raw_path in paths:
        path = str(raw_path)
        try:
            usage = shutil.disk_usage(path)
            usage_path = path
            warning = ""
        except OSError as exc:
            candidate = Path(path)
            while not candidate.exists() and candidate.parent != candidate:
                candidate = candidate.parent
            if not candidate.exists():
                result.append({"path": path, "error": str(exc)})
                continue
            try:
                usage = shutil.disk_usage(candidate)
            except OSError as fallback_exc:
                result.append({"path": path, "error": str(fallback_exc)})
                continue
            usage_path = str(candidate)
            warning = (
                f"{path} does not exist; showing filesystem usage from {usage_path}"
            )
        result.append(
            {
                "path": path,
                "usage_path": usage_path,
                "warning": warning,
                "total_bytes": usage.total,
                "used_bytes": usage.used,
                "available_bytes": usage.free,
            }
        )
    return result


def collect_logged_users() -> dict[str, Any]:
    try:
        result = subprocess.run(
            ["who"],
            check=False,
            capture_output=True,
            text=True,
            timeout=3,
        )
    except (FileNotFoundError, OSError, subprocess.TimeoutExpired) as exc:
        return {"sessions": 0, "unique_users": 0, "error": str(exc)}

    users = []
    for line in result.stdout.splitlines():
        fields = line.split()
        if fields:
            users.append(fields[0])
    return {
        "sessions": len(users),
        "unique_users": len(set(users)),
    }


def service_state(unit: str) -> dict[str, Any]:
    if not re.fullmatch(r"[A-Za-z0-9_.@-]+", unit):
        return {"state": "invalid", "active": False}
    try:
        result = subprocess.run(
            ["systemctl", "is-active", unit],
            check=False,
            capture_output=True,
            text=True,
            timeout=3,
        )
    except (FileNotFoundError, OSError, subprocess.TimeoutExpired) as exc:
        return {"state": "unknown", "active": False, "error": str(exc)}
    state = result.stdout.strip() or "inactive"
    return {"state": state, "active": state == "active"}


def local_tcp_listener(address: str, port: int) -> tuple[bool, str]:
    try:
        result = subprocess.run(
            ["ss", "-ltn"],
            check=False,
            capture_output=True,
            text=True,
            timeout=3,
        )
    except (FileNotFoundError, OSError, subprocess.TimeoutExpired) as exc:
        return False, str(exc)
    if result.returncode != 0:
        return False, result.stderr.strip() or "ss failed"

    expected_port = str(port)
    for line in result.stdout.splitlines():
        fields = line.split()
        if len(fields) < 4:
            continue
        endpoint = fields[3]
        if not endpoint.rsplit(":", 1)[-1] == expected_port:
            continue
        endpoint_address = endpoint.rsplit(":", 1)[0].strip("[]")
        if endpoint_address in {address, "0.0.0.0", "::", "*"}:
            return True, ""
    return False, f"no local listener on {address}:{port}"


def _tcp_endpoint(value: str) -> tuple[str, str] | None:
    endpoint = value.strip()
    if endpoint.startswith("["):
        closing = endpoint.rfind("]:")
        if closing <= 1:
            return None
        return endpoint[1:closing], endpoint[closing + 2 :]

    address, separator, port = endpoint.rpartition(":")
    if not separator or not address or not port:
        return None
    return address, port


def _established_tcp_connection(
    local_address: str, peer_address: str, port: int
) -> tuple[bool, str]:
    try:
        result = subprocess.run(
            ["ss", "-Htn", "state", "established"],
            check=False,
            capture_output=True,
            text=True,
            timeout=3,
        )
    except (FileNotFoundError, OSError, subprocess.TimeoutExpired) as exc:
        return False, str(exc)
    if result.returncode != 0:
        return False, result.stderr.strip() or "ss failed"

    expected_port = str(port)
    for line in result.stdout.splitlines():
        fields = line.split()
        if len(fields) < 2:
            continue
        local_endpoint = _tcp_endpoint(fields[-2])
        peer_endpoint = _tcp_endpoint(fields[-1])
        if (
            local_endpoint
            and peer_endpoint
            and local_endpoint[0] == local_address
            and peer_endpoint == (peer_address, expected_port)
        ):
            return True, ""
    return (
        False,
        "no established TCP connection from "
        f"{local_address} to {peer_address}:{port}",
    )


def collect_network(
    config: dict[str, Any], role: str | None = None
) -> dict[str, Any]:
    iface = str(config.get("cluster_iface", ""))
    result: dict[str, Any] = {"interface": iface}
    if iface:
        result["operstate"] = _read_text(f"/sys/class/net/{iface}/operstate") or "missing"
        result["mtu"] = _read_int(f"/sys/class/net/{iface}/mtu")
        result["speed_mbps"] = _read_int(f"/sys/class/net/{iface}/speed")
    rpc_port = _as_int(config.get("rpc_port"), 50053)
    local_ip = str(config.get("local_ip", ""))
    peer_ip = str(config.get("peer_ip", ""))
    if role == "peer":
        reachable, error = local_tcp_listener(local_ip, rpc_port)
        result["rpc_reachable"] = reachable
        if error:
            result["rpc_error"] = error
    elif peer_ip:
        reachable, error = _established_tcp_connection(
            local_ip, peer_ip, rpc_port
        )
        result["rpc_reachable"] = reachable
        if error:
            result["rpc_error"] = error
    return result


def collect_llama(config: dict[str, Any]) -> dict[str, Any]:
    base_url = str(config.get("llama_url", "")).rstrip("/")
    if not base_url:
        return {"configured": False}

    result: dict[str, Any] = {"configured": True, "url": base_url}
    health_status, health_body = http_json(f"{base_url}/health", timeout=3)
    result["health"] = {"status_code": health_status, "body": health_body}
    if health_status != 200:
        result["ready"] = False
        return result

    props_status, props_body = http_json(f"{base_url}/props", timeout=5)
    if props_status == 200 and isinstance(props_body, dict):
        defaults = _mapping(props_body.get("default_generation_settings"))
        result["total_slots"] = props_body.get("total_slots")
        result["aggregate_context"] = defaults.get("n_ctx")
        result["model_path"] = props_body.get("model_path")
        result["build_info"] = props_body.get("build_info")
    else:
        result["props_error"] = props_body

    slots_status, slots_body = http_json(f"{base_url}/slots", timeout=5)
    if slots_status == 200 and isinstance(slots_body, list):
        slots = []
        for slot in slots_body:
            if not isinstance(slot, dict):
                continue
            slots.append(
                {
                    "id": slot.get("id"),
                    "n_ctx": slot.get("n_ctx"),
                    "is_processing": bool(slot.get("is_processing")),
                    "n_decoded": _mapping(slot.get("next_token")).get("n_decoded"),
                }
            )
        result["slots"] = slots
        result["active_slots"] = sum(
            1 for slot in slots if slot["is_processing"]
        )
    else:
        result["slots_error"] = slots_body

    models_status, models_body = http_json(f"{base_url}/v1/models", timeout=5)
    if models_status == 200 and isinstance(models_body, dict):
        result["models"] = [
            item.get("id")
            for item in models_body.get("data", [])
            if isinstance(item, dict) and item.get("id")
        ]
    else:
        result["models_error"] = models_body

    result["ready"] = True
    return result


def collect_node_snapshot(
    config: dict[str, Any], role: str | None = None
) -> dict[str, Any]:
    node_role = role or str(config.get("role", "unknown"))
    services = {
        str(unit): service_state(str(unit))
        for unit in config.get("services", [])
        if str(unit)
    }
    llama = collect_llama(config) if config.get("llama_url") else None
    network = collect_network(config, role=node_role)
    users = collect_logged_users()
    active_slots = None
    slot_capacity = None
    if isinstance(llama, dict):
        active_slots = llama.get("active_slots")
        slot_capacity = llama.get("total_slots")

    errors: list[str] = []
    if llama and not llama.get("ready", False):
        errors.append("llama-server is not ready")
    if node_role == "peer":
        rpc_state = services.get("qwen3d8-rpc.service", {})
        if rpc_state and not rpc_state.get("active", False):
            errors.append("qwen3d8-rpc.service is not active")
    if network.get("rpc_reachable") is False:
        errors.append(
            f"RPC endpoint is unreachable: {network.get('rpc_error', 'connection failed')}"
        )
    if network.get("operstate") not in {None, "up", "unknown"}:
        errors.append(f"{network['interface']} is {network['operstate']}")

    get_load_average = getattr(os, "getloadavg", None)
    if callable(get_load_average):
        try:
            load_average = list(get_load_average())
        except OSError:
            load_average = []
    else:
        load_average = []
    uptime_seconds = None
    uptime_text = _read_text("/proc/uptime")
    if uptime_text:
        try:
            uptime_seconds = float(uptime_text.split()[0])
        except (IndexError, ValueError):
            uptime_seconds = None

    return {
        "schema_version": 1,
        "collected_at": utc_now(),
        "hostname": socket.gethostname(),
        "role": node_role,
        "status": "healthy" if not errors else "degraded",
        "errors": errors,
        "memory": collect_memory(),
        "temperatures": collect_temperatures(),
        "fans": collect_fans(),
        "gpu_memory": collect_gpu_memory(),
        "disk": collect_disk_usage(list(config.get("paths", []))),
        "users": {
            **users,
            "active_inference": active_slots,
            "inference_capacity": slot_capacity,
            "identity_note": (
                "llama.cpp exposes active slots, not authenticated human identities"
            ),
        },
        "services": services,
        "network": network,
        "load_average": load_average,
        "uptime_seconds": uptime_seconds,
        "inference": llama,
    }


def collect_cluster_snapshots(
    config: dict[str, Any]
) -> tuple[dict[str, Any], list[str]]:
    """Collect the controller and worker snapshots for the dashboard."""

    local = collect_node_snapshot(config)
    nodes = [local]
    errors: list[str] = []
    peer_url = str(config.get("peer_agent_url", "")).rstrip("/")
    if peer_url:
        headers: dict[str, str] = {}
        token = read_token(config.get("peer_agent_token_file"))
        if token:
            headers["X-Cluster-Agent-Token"] = token
        status, body = http_json(f"{peer_url}/metrics", timeout=5, headers=headers)
        if status == 200 and isinstance(body, dict):
            nodes.append(body)
        else:
            message = body.get("error", body) if isinstance(body, dict) else body
            errors.append(f"worker agent unavailable ({status}): {message}")
            nodes.append(
                {
                    "schema_version": 1,
                    "hostname": str(config.get("peer_ip", "worker")),
                    "role": "peer",
                    "status": "unreachable",
                    "errors": [errors[-1]],
                    "memory": {},
                    "temperatures": [],
                    "fans": [],
                    "gpu_memory": {},
                    "disk": [],
                    "users": {},
                    "services": {},
                    "network": {},
                    "inference": None,
                }
            )
    else:
        errors.append("peer_agent_url is not configured")

    known_errors = set(errors)
    for node in nodes:
        if not isinstance(node, dict):
            continue
        hostname = str(node.get("hostname", node.get("role", "node")))
        node_errors = node.get("errors", [])
        if isinstance(node_errors, list):
            for node_error in node_errors:
                if isinstance(node_error, str):
                    message = f"{hostname}: {node_error}"
                    if message not in known_errors:
                        errors.append(message)
                        known_errors.add(message)
        if node.get("status") not in {None, "healthy"} and not node_errors:
            message = f"{hostname}: status={node.get('status', 'unknown')}"
            if message not in known_errors:
                errors.append(message)
                known_errors.add(message)

    active_users = 0
    capacity = 0
    for node in nodes:
        if not isinstance(node, dict):
            continue
        users = _mapping(node.get("users"))
        active = users.get("active_inference")
        node_capacity = users.get("inference_capacity")
        if isinstance(active, int):
            active_users += active
        if isinstance(node_capacity, int):
            capacity += node_capacity

    cluster = {
        "collected_at": utc_now(),
        "status": (
            "healthy"
            if not errors and all(node.get("status") == "healthy" for node in nodes)
            else "degraded"
        ),
        "active_inference_users": active_users,
        "inference_capacity": capacity or None,
        "nodes": nodes,
        "errors": errors,
    }
    return cluster, errors


def format_bytes(value: Any) -> str:
    try:
        number = float(value)
    except (TypeError, ValueError):
        return "n/a"
    if number < 1024:
        return f"{number:.0f} B"
    units = ("KiB", "MiB", "GiB", "TiB")
    for unit in units:
        number /= 1024
        if number < 1024 or unit == units[-1]:
            return f"{number:.1f} {unit}"
    return "n/a"


def format_temperature(readings: Any) -> str:
    if not isinstance(readings, list) or not readings:
        return "n/a"
    values = [
        item.get("celsius")
        for item in readings
        if isinstance(item, dict) and isinstance(item.get("celsius"), (int, float))
    ]
    if not values:
        return "n/a"
    return f"{max(values):.1f} C max"


def format_fans(readings: Any) -> str:
    if not isinstance(readings, list) or not readings:
        return "n/a"
    values = [
        item.get("rpm")
        for item in readings
        if isinstance(item, dict) and isinstance(item.get("rpm"), (int, float))
    ]
    if not values:
        return "n/a"
    return ", ".join(f"{int(value)} RPM" for value in values)
